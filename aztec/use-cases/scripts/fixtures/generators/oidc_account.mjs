// Writes src/fixture.nr and fixtures/manifest.json of an OIDC
// account (account-authorisation/<provider>): a synthetic ID token whose
// nonce is the lowercase hex of the action hash, under a public synthetic
// test key. The provider module oidc_account/<provider>.mjs builds the
// token with the repository's credential library (packages/credential-proofs-inputs).
//
// node scripts/fixtures/generators/oidc_account.mjs --instance account-authorisation/<provider> --action <field hex>
//
// Needs `npm ci && npm run build` in packages/credential-proofs-inputs. No network,
// no proving. The tokens are synthetic: they are not provider credentials.
import { options, write } from "./account.mjs";

const values = options();
const provider = values.instance.split("/")[1];
const { default: make } = await import(`./oidc_account/${provider}.mjs`);
const made = await make({ action: values.action });
const fixture = `//! Generated by scripts/fixtures/generators/oidc_account.mjs; see fixtures/manifest.json. Do not edit.
//! ${made.summary}
use crate::${made.contract}::{AuthInput, AuthPolicy};

/// The action hash whose lowercase hex the token carries as its nonce.
pub global ACTION: Field = 0x${values.action};
/// The verifier time the token was made for, and its exclusive expiry.
pub global NOW: u64 = ${made.now};
pub global EXPIRY: u64 = ${made.expiry};
${made.extra ?? ""}
pub fn auth() -> AuthInput {
${made.auth}
}
`;
await write({
  instance: values.instance,
  generator: "oidc_account.mjs",
  argv: ["--action", values.action],
  library: made.library,
  inputs: [
    ...made.inputs,
    `aztec/use-cases/scripts/fixtures/generators/oidc_account/${provider}.mjs`,
    ...(made.moduleInputs ?? []),
  ],
  keyProvenance: made.keyProvenance,
  claims: made.claims,
  notes: made.notes,
  fixture,
});
