// Writes src/fixture.nr and fixtures/manifest.json of account-authorisation/passkey:
// a synthetic WebAuthn assertion (P-256, RFC 6979, low s) over the action hash.
//
// node scripts/fixtures/generators/passkey.mjs --instance account-authorisation/passkey --action <field hex>
//
// The P-256 key is derived from a public seed; it is not an authenticator key.
// Needs `npm ci` in aztec/use-cases (@noble/curves).
import { createHash } from "node:crypto";
import {
  array,
  credentials,
  options,
  padded,
  require,
  seed,
  write,
} from "./account.mjs";

const RP_ID = "example.com";
const ORIGIN = "https://example.com";

const values = options();
const { p256 } = require("@noble/curves/p256");
const key = seed("passkey account key v1");
const other = seed("passkey account other key v1");
const point = (secret) => Buffer.from(p256.getPublicKey(secret, false));
const publicKey = point(key);
const otherKey = point(other);
const action = Buffer.from(values.action, "hex");
const clientData = Buffer.from(
  JSON.stringify({
    type: "webauthn.get",
    challenge: action.toString("base64url"),
    origin: ORIGIN,
    crossOrigin: false,
  }),
);
// rpIdHash || flags (user present, user verified) || signature counter 1.
const authenticatorData = Buffer.concat([
  createHash("sha256").update(RP_ID).digest(),
  Buffer.from([0x05, 0, 0, 0, 1]),
]);
const signed = createHash("sha256")
  .update(
    Buffer.concat([
      authenticatorData,
      createHash("sha256").update(clientData).digest(),
    ]),
  )
  .digest();
const signature = Buffer.from(
  p256.sign(signed, key, { lowS: true }).toCompactRawBytes(),
);
const bytes = (buffer, indent = "        ") => array([...buffer], indent);

const fixture = `//! Generated by scripts/fixtures/generators/passkey.mjs; see fixtures/manifest.json. Do not edit.
//! A synthetic WebAuthn assertion under a P-256 key derived from a public
//! seed. It is not an authenticator credential; anyone can sign with it.
use crate::PasskeyAccount::{AuthInput, AuthPolicy};

/// The action hash that the assertion's challenge carries.
pub global ACTION: Field = 0x${values.action};

/// Another P-256 public key (also from a public seed). Nothing is signed under it.
pub global OTHER_KEY_X: [u8; 32] = ${bytes(otherKey.subarray(1, 33), "")};
pub global OTHER_KEY_Y: [u8; 32] = ${bytes(otherKey.subarray(33, 65), "")};

pub fn auth() -> AuthInput {
    AuthInput {
        policy: AuthPolicy {
            key_x: ${bytes(publicKey.subarray(1, 33), "            ")},
            key_y: ${bytes(publicKey.subarray(33, 65), "            ")},
            rp_id: ${padded(Buffer.from(RP_ID), 64, "            ")},
            rp_id_len: ${RP_ID.length},
            origin: ${padded(Buffer.from(ORIGIN), 128, "            ")},
            origin_len: ${ORIGIN.length},
            require_user_verification: true,
        },
        authenticator_data: ${bytes(authenticatorData)},
        client_data_json: ${padded(clientData, 256, "        ")},
        client_data_json_len: ${clientData.length},
        signature: ${bytes(signature)},
    }
}
`;

await write({
  instance: values.instance,
  generator: "passkey.mjs",
  argv: ["--action", values.action],
  library: `aztec/use-cases dependencies @noble/curves p256 (RFC 6979, low s)`,
  inputs: [],
  keyProvenance:
    "P-256 keys derived as sha256('credential-proofs synthetic passkey account key v1') and '... other key v1'; public seeds, not authenticator keys. Anyone can sign with them.",
  claims: {
    rp_id: RP_ID,
    origin: ORIGIN,
    flags: "0x05 (UP, UV)",
    sign_count: 1,
    client_data_json: clientData.toString(),
  },
  fixture,
});
