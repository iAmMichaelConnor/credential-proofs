// Writes src/fixture.nr and fixtures/manifest.json of
// account-authorisation/twitter_reclaim: synthetic Reclaim envelopes whose
// signed context names the account, the action hash, the enrolled username
// and a session, signed by a synthetic attestor key.
//
// node scripts/fixtures/generators/reclaim.mjs --instance account-authorisation/twitter_reclaim \
//     --account <field hex> --action <field hex> --next-action <field hex>
//
// Three envelopes: the action with session-1, the next action (tx nonce + 1)
// with session-1, and the next action with session-2. The attestor key is
// derived from a public seed; it is not a Reclaim attestor. Needs `npm ci` in
// packages/credential-proofs-inputs (viem). The account and
// the session are arguments.
import {
  array,
  credentials,
  padded,
  require,
  seed,
  write,
} from "./account.mjs";
import { parseArgs } from "node:util";

const { values } = parseArgs({
  options: {
    instance: { type: "string" },
    account: { type: "string" },
    action: { type: "string" },
    "next-action": { type: "string" },
  },
});
const field = (v) => {
  const hex = (v ?? "").replace(/^0x/, "").toLowerCase().padStart(64, "0");
  if (!/^[0-9a-f]{64}$/.test(hex))
    throw new Error("Pass --account, --action and --next-action as field hex");
  return hex;
};
const [account, action, nextAction] = [
  values.account,
  values.action,
  values["next-action"],
].map(field);
const { privateKeyToAccount } = require("viem/accounts");
const { keccak256, toBytes } = require("viem");

const USERNAME = "test_user";
const PROVIDER_HASH = `0x${"2a".repeat(32)}`;
const OWNER = "0x0000000000000000000000000000000000000000";
const TIMESTAMP = 1_900_000_000;
const EPOCH = 1;
const MAX_AGE = 60;
const attestor = privateKeyToAccount(
  `0x${seed("reclaim account attestor key v1").toString("hex")}`,
);
const other = privateKeyToAccount(
  `0x${seed("reclaim account other attestor key v1").toString("hex")}`,
);
const bytes = (buffer, indent = "        ") => array([...buffer], indent);
const hex = (value, length) =>
  Buffer.from(value.replace(/^0x/, ""), "hex").subarray(0, length);

async function envelope(actionHex, session) {
  const context = JSON.stringify({
    contextAddress: `0x${account}`,
    contextMessage: actionHex,
    extractedParameters: { username: USERNAME },
    providerHash: PROVIDER_HASH,
    reclaimSessionId: session,
  });
  const identifier = keccak256(toBytes(`http\n{}\n${context}`));
  const message = `${identifier}\n${OWNER}\n${TIMESTAMP}\n${EPOCH}`;
  const signature = hex(
    await attestor.signMessage({ message: { raw: toBytes(message) } }),
    65,
  );
  return { context, identifier, signature };
}
const main = await envelope(action, "session-1");
const sameSession = await envelope(nextAction, "session-1");
const nextSession = await envelope(nextAction, "session-2");
const point = (a) => hex(a.publicKey, 65);
const pieces = (e, name) => `/// ${name}
pub fn ${name}_context() -> [u8; 1024] ${"{"}
    ${padded(Buffer.from(e.context), 1024, "    ")}
}
pub global ${name.toUpperCase()}_CONTEXT_LEN: u32 = ${Buffer.byteLength(e.context)};
pub global ${name.toUpperCase()}_IDENTIFIER: [u8; 32] = ${bytes(hex(e.identifier, 32), "")};
pub global ${name.toUpperCase()}_SIGNATURE: [u8; 65] = ${bytes(e.signature, "")};
`;

const fixture = `//! Generated by scripts/fixtures/generators/reclaim.mjs; see fixtures/manifest.json. Do not edit.
//! Synthetic Reclaim envelopes under a secp256k1 attestor key derived from a
//! public seed. They are not Reclaim attestations; anyone can sign with the key.
use crate::TwitterReclaimAccount::{AuthInput, AuthPolicy};

/// The account address and actions that the signed contexts name.
pub global ACCOUNT: Field = 0x${account};
pub global ACTION: Field = 0x${action};
pub global NEXT_ACTION: Field = 0x${nextAction};
/// The signed claim time; the policy accepts claims at most 60 s old.
pub global NOW: u64 = ${TIMESTAMP};

/// Another attestor key (from a public seed). Nothing is signed under it.
pub global OTHER_ATTESTOR_X: [u8; 32] = ${bytes(point(other).subarray(1, 33), "")};
pub global OTHER_ATTESTOR_Y: [u8; 32] = ${bytes(point(other).subarray(33, 65), "")};
pub global OTHER_ATTESTOR_ADDRESS: [u8; 20] = ${bytes(hex(other.address, 20), "")};

${pieces(sameSession, "next_same_session")}
${pieces(nextSession, "next_session")}
/// The session id of \`next_session\`.
pub fn next_session_id() -> [u8; 128] {
    ${padded(Buffer.from("session-2"), 128, "    ")}
}

pub fn auth() -> AuthInput {
    AuthInput {
        policy: AuthPolicy {
            // keccak256("{}"), the approved parameters of this synthetic profile.
            parameters_hash: ${bytes(hex(keccak256(toBytes("{}")), 32), "            ")},
            provider_hash: ${bytes(hex(PROVIDER_HASH, 32), "            ")},
            username: ${padded(Buffer.from(USERNAME), 15, "            ")},
            username_len: ${USERNAME.length},
            attestor_x: ${bytes(point(attestor).subarray(1, 33), "            ")},
            attestor_y: ${bytes(point(attestor).subarray(33, 65), "            ")},
            attestor_address: ${bytes(hex(attestor.address, 20), "            ")},
            epoch: ${EPOCH},
            max_age_seconds: ${MAX_AGE},
        },
        provider: ${padded(Buffer.from("http"), 8, "        ")},
        provider_len: 4,
        parameters: ${padded(Buffer.from("{}"), 1024, "        ")},
        parameters_len: 2,
        context: ${padded(Buffer.from(main.context), 1024, "        ")},
        context_len: ${Buffer.byteLength(main.context)},
        reclaim_session_id: ${padded(Buffer.from("session-1"), 128, "        ")},
        reclaim_session_id_len: 9,
        owner: ${bytes(Buffer.from(OWNER))},
        timestamp_s: ${TIMESTAMP},
        epoch: ${EPOCH},
        identifier: ${bytes(hex(main.identifier, 32))},
        signature: ${bytes(main.signature)},
    }
}
`;

await write({
  instance: values.instance,
  generator: "reclaim.mjs",
  argv: ["--account", account, "--action", action, "--next-action", nextAction],
  library: `aztec/use-cases dependencies viem (EIP-191 signMessage over the Reclaim identifier, owner, timestamp and epoch)`,
  inputs: [`${credentials}/src/reclaim.ts`],
  keyProvenance:
    "secp256k1 attestor keys sha256('credential-proofs synthetic reclaim account attestor key v1') and '... other attestor key v1'; public seeds, not Reclaim attestors. Anyone can sign with them.",
  claims: {
    attestor: attestor.address,
    context: main.context,
    identifier: main.identifier,
    timestamp: TIMESTAMP,
    epoch: EPOCH,
  },
  fixture,
});
