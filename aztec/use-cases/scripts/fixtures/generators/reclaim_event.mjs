// Writes src/fixture.nr and fixtures/manifest.json of
// event-proof/twitter_reclaim: three synthetic Reclaim claim envelopes (the
// wire format of noir/reclaim_auth) for an HTTP provider
// whose parameters name a Twitter/X URL and a response rule. A synthetic
// attestor key, derived from a public seed, signs them with EIP-191. No
// Reclaim attestor observed anything, and X was not contacted.
//
// node scripts/fixtures/generators/reclaim_event.mjs --instance event-proof/twitter_reclaim [--now <unix s>]
//
// Needs `npm ci` in aztec/use-cases (viem). No network access,
// no proving.
import { createHash } from "node:crypto";
import { parseArgs } from "node:util";
import {
  array,
  credentials,
  instanceRow,
  padded,
  require,
  writeFixture,
} from "./event.mjs";

const generator = "aztec/use-cases/scripts/fixtures/generators/reclaim_event.mjs";
const { privateKeyToAccount } = require("viem/accounts");
const { keccak256, toBytes, hexToBytes } = require("viem");

const PROVIDER = "http";
const PARAMETERS = JSON.stringify({
  method: "GET",
  responseMatches: [{ type: "contains", value: '"full_text":"gm aztec"' }],
  url: "https://api.x.com/2/tweets/1900000000000000001",
});
const contextFor = (session) =>
  JSON.stringify({
    contextAddress: "0x0",
    contextMessage: "event",
    extractedParameters: {},
    reclaimSessionId: session,
  });
const OWNER = "0x00000000000000000000000000000000000000aa";
const OTHER_OWNER = "0x00000000000000000000000000000000000000bb";
const EPOCH = 1;
const AGE = 60;

const { values } = parseArgs({
  options: {
    instance: { type: "string" },
    now: { type: "string", default: "4000000000" },
  },
});
const now = Number(values.now);
if (!Number.isSafeInteger(now) || now <= AGE || now >= 2 ** 32)
  throw new Error("--now must be a Unix time in seconds below 2^32");
const { useCase, scheme, adapter } = await instanceRow(
  values.instance,
  "twitter_reclaim",
);

const seed = (label) => `0x${createHash("sha256").update(label).digest("hex")}`;
const attestor = privateKeyToAccount(
  seed("credential-proofs reclaim event attestor key v1"),
);
const other = privateKeyToAccount(
  seed("credential-proofs reclaim event other attestor key v1"),
);
const point = (account) => {
  const key = hexToBytes(account.publicKey);
  if (key.length !== 65 || key[0] !== 4)
    throw new Error("Expected an uncompressed key");
  return {
    x: [...key.slice(1, 33)],
    y: [...key.slice(33)],
    address: [...hexToBytes(account.address)],
  };
};
const text = (value) => [...Buffer.from(value, "utf8")];

async function claim(session, timestamp, owner = OWNER) {
  const context = contextFor(session);
  const identifier = keccak256(
    toBytes(`${PROVIDER}\n${PARAMETERS}\n${context}`),
  );
  const message = `${identifier}\n${owner}\n${timestamp}\n${EPOCH}`;
  const signature = await attestor.signMessage({ message });
  return { context, identifier, signature, timestamp, owner };
}
const timestamp = now - AGE;
const first = await claim("session-1", timestamp);
const second = await claim("session-2", timestamp);
const resigned = await claim("session-1", timestamp + 1, OTHER_OWNER);
const key = point(attestor);
const otherKey = point(other);
const parametersHash = [...hexToBytes(keccak256(toBytes(PARAMETERS)))];
const observation = (name, c) => `pub fn ${name}() -> ReclaimObservation {
    ReclaimObservation {
        attestor_x: ${array(key.x)},
        attestor_y: ${array(key.y)},
        attestor_address: ${array(key.address)},
        epoch: ${EPOCH},
        provider: ${padded(text(PROVIDER), 8)},
        provider_len: ${text(PROVIDER).length},
        parameters: ${padded(text(PARAMETERS), 1024)},
        parameters_len: ${text(PARAMETERS).length},
        parameters_hash: ${array(parametersHash)},
        context: ${padded(text(c.context), 512)},
        context_len: ${text(c.context).length},
        owner: ${array(text(c.owner))},
        timestamp_s: ${c.timestamp},
        identifier: ${array(hexToBytes(c.identifier))},
        signature: ${array(hexToBytes(c.signature))},
    }
}
`;
const fixture = `//! Generated by scripts/fixtures/generators/reclaim_event.mjs; see fixtures/manifest.json. Do not edit.
//! Three synthetic Reclaim claims signed by a synthetic attestor key derived
//! from a public seed. No Reclaim attestor signed them; X was not contacted.
use ${adapter.crate}::ReclaimObservation;

/// The verifier time the claims were made for.
pub global NOW: u64 = ${now};
/// The claim time of \`claim()\` and \`second_claim()\`.
pub global CLAIMED_AT: u64 = ${timestamp};

/// Another attestor key (another public seed). No claim is signed under it.
pub global OTHER_ATTESTOR_X: [u8; 32] = ${array(otherKey.x, "")};
pub global OTHER_ATTESTOR_Y: [u8; 32] = ${array(otherKey.y, "")};
pub global OTHER_ATTESTOR_ADDRESS: [u8; 20] = ${array(otherKey.address, "")};

/// Provider "${PROVIDER}", the fixture parameters, session "session-1".
${observation("claim", first)}
/// The same provider and parameters with session "session-2": another claim.
${observation("second_claim", second)}
/// The claim of \`claim()\` (same identifier) signed again one second later
/// for another owner: the same event.
${observation("resigned_claim", resigned)}`;

await writeFixture({
  instance: values.instance,
  useCase,
  scheme,
  fixture,
  inputs: [generator, "aztec/use-cases/scripts/fixtures/generators/event.mjs"],
  record: {
    kind: "synthetic",
    generator: {
      argv: [
        "node",
        "scripts/fixtures/generators/reclaim_event.mjs",
        "--instance",
        values.instance,
        "--now",
        String(now),
      ],
      cwd: "aztec/use-cases",
      library:
        "viem (aztec/use-cases dependencies) keccak256 and EIP-191 signMessage over the Reclaim wire format",
    },
    key_provenance:
      "Synthetic secp256k1 attestor keys: sha256 of the public seeds 'credential-proofs reclaim event attestor key v1' and '... other attestor key v1'. Not Reclaim attestor keys. Anyone can derive them.",
    claims: {
      provider: PROVIDER,
      parameters: PARAMETERS,
      contexts: [first.context, second.context],
      identifiers: [first.identifier, second.identifier],
      owners: [OWNER, OWNER, OTHER_OWNER],
      timestamps_s: [timestamp, timestamp, timestamp + 1],
      epoch: EPOCH,
      attestor_address: attestor.address,
    },
    notes: [
      `The claim time is ${AGE} s before --now.`,
      "The parameters name an X URL, but no X response was fetched or matched: the envelope is synthetic.",
      "Negative cases mutate this fixture in src/test.nr.",
    ],
  },
});
