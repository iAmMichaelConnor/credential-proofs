// Writes src/fixture.nr and fixtures/manifest.json of account-authorisation/zkemail:
// a synthetic DKIM (rsa-sha256, simple/simple, h=from) signature over the
// action mail `CRED-PROOF-ACTION:<action hex>` from alice@service.example.
//
// node scripts/fixtures/generators/zkemail.mjs --instance account-authorisation/zkemail --action <field hex>
//
// The key is the public synthetic RS256 test key in
// fixtures/data; it is not a mail domain's key.
import {
  createHash,
  createPrivateKey,
  createPublicKey,
  sign,
} from "node:crypto";
import { readFile } from "node:fs/promises";
import {
  array,
  credentials,
  options,
  padded,
  repository,
  write,
} from "./account.mjs";

const SENDER = "alice@service.example";
const DOMAIN = "service.example";
const SELECTOR = "s1";
const values = options();
const pem = await readFile(
  `${repository}fixtures/data/synthetic-rs256-private.pem`,
);
const key = createPrivateKey(pem);
const jwk = createPublicKey(key).export({ format: "jwk" });
const big = (b64) =>
  BigInt(`0x${Buffer.from(b64, "base64url").toString("hex")}`);
const limbs = (value) =>
  Array.from({ length: 18 }, (_, i) =>
    ((value >> (120n * BigInt(i))) & ((1n << 120n) - 1n)).toString(),
  );
const n = big(jwk.n);
const body = `CRED-PROOF-ACTION:${values.action}\r\n`;
const bh = createHash("sha256").update(body).digest("base64");
const header = `from:${SENDER}\r\ndkim-signature:v=1; a=rsa-sha256; c=simple/simple; d=${DOMAIN}; s=${SELECTOR}; h=from; bh=${bh}; b=`;
const signature = BigInt(
  `0x${sign("sha256", Buffer.from(header), key).toString("hex")}`,
);
// Another well-formed modulus (n + 2) with its own Barrett parameter. Nothing is signed under it.
const other = n + 2n;

const fixture = `//! Generated by scripts/fixtures/generators/zkemail.mjs; see fixtures/manifest.json. Do not edit.
//! A synthetic DKIM signature under the public synthetic RS256 test key in
//! fixtures/data. It is not a mail domain's key; anyone can sign with it.
use crate::DkimAccount::{AuthInput, AuthPolicy};

/// The action hash that the signed mail body carries as hex.
pub global ACTION: Field = 0x${values.action};

/// Another well-formed 2048-bit modulus (the key's modulus + 2) and its
/// Barrett parameter. Nothing is signed under it.
pub global OTHER_MODULUS: [Field; 18] = ${array(limbs(other), "")};
pub global OTHER_REDC: [Field; 18] = ${array(limbs((1n << 4102n) / other), "")};

pub fn auth() -> AuthInput {
    AuthInput {
        policy: AuthPolicy {
            modulus: ${array(limbs(n), "            ")},
            redc: ${array(limbs((1n << 4102n) / n), "            ")},
            sender: ${padded(Buffer.from(SENDER), 96, "            ")},
            sender_len: ${SENDER.length},
            service_domain: ${padded(Buffer.from(DOMAIN), 64, "            ")},
            service_domain_len: ${DOMAIN.length},
            selector: ${padded(Buffer.from(SELECTOR), 64, "            ")},
            selector_len: ${SELECTOR.length},
        },
        signature: ${array(limbs(signature), "        ")},
    }
}
`;

await write({
  instance: values.instance,
  generator: "zkemail.mjs",
  argv: ["--action", values.action],
  library:
    "node:crypto RSA-SHA256 PKCS#1 v1.5 over the DKIM signing input of the account's profile.nr",
  inputs: [
    `fixtures/data/synthetic-rs256-private.pem`,
    `fixtures/data/synthetic-rs256-public.pem`,
  ],
  keyProvenance: `Public synthetic RS256 test key committed in fixtures/data; not a mail domain's DKIM key. Anyone can sign with it.`,
  claims: { from: SENDER, d: DOMAIN, s: SELECTOR, body, signing_input: header },
  fixture,
});
