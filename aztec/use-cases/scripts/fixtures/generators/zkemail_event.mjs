// Writes src/fixture.nr and fixtures/manifest.json of event-proof/zkemail:
// two synthetic received emails in the adapter's DKIM profile (relaxed
// from:to:subject, see adapters/zkemail/src/lib.nr), signed with RSA-SHA256
// PKCS#1 v1.5 under the public synthetic RS256 test key in
// fixtures/data. The emails are synthetic: no mail
// domain signed them, and anyone can sign with the key.
//
// node scripts/fixtures/generators/zkemail_event.mjs --instance event-proof/zkemail [--now <unix s>]
//
// Needs only node:crypto. No network access, no proving.
import { createPublicKey, createSign, createVerify } from "node:crypto";
import { readFile } from "node:fs/promises";
import { parseArgs } from "node:util";
import {
  array,
  bounded,
  credentials,
  instanceRow,
  limbs,
  repository,
  sha256,
  writeFixture,
} from "./event.mjs";

const generator = "aztec/use-cases/scripts/fixtures/generators/zkemail_event.mjs";
const DOMAIN = "mail.example";
const SELECTOR = "s1";
const SENDER = `alerts@${DOMAIN}`;
const RECIPIENT = "bob@inbox.example";
const SUBJECT = "Order 42 shipped";
const BODY = "Your order 42 has shipped.\r\n";
// The emails are signed this long before the verifier time.
const AGE = 60;

const { values } = parseArgs({
  options: {
    instance: { type: "string" },
    now: { type: "string", default: "4000000000" },
  },
});
const now = Number(values.now);
if (!Number.isSafeInteger(now) || now <= AGE)
  throw new Error("--now must be a Unix time in seconds");
const { useCase, scheme, adapter } = await instanceRow(
  values.instance,
  "zkemail",
);

const keys = `fixtures/data`;
const privatePem = await readFile(
  `${repository}${keys}/synthetic-rs256-private.pem`,
  "utf8",
);
const publicPem = await readFile(
  `${repository}${keys}/synthetic-rs256-public.pem`,
  "utf8",
);
const jwk = createPublicKey(publicPem).export({ format: "jwk" });
const big = (bytes) => BigInt(`0x${Buffer.from(bytes).toString("hex")}`);
const modulus = big(Buffer.from(jwk.n, "base64url"));
if (modulus >> 2047n !== 1n)
  throw new Error("The test key is not a 2048-bit key");
// Barrett parameter of noir-bignum for a 2048-bit modulus.
const redc = (n) => (1n << 4102n) / n;

const bodyHash = Buffer.from(sha256(Buffer.from(BODY, "latin1")), "hex");
const signingInput = (signedAt) =>
  `from:${SENDER}\r\nto:${RECIPIENT}\r\nsubject:${SUBJECT}\r\n` +
  `dkim-signature:v=1; a=rsa-sha256; c=relaxed/relaxed; d=${DOMAIN}; s=${SELECTOR}; ` +
  `t=${signedAt}; h=from:to:subject; bh=${bodyHash.toString("base64")}; b=`;
function sign(signedAt) {
  const input = Buffer.from(signingInput(signedAt), "latin1");
  const signature = createSign("RSA-SHA256").update(input).sign(privatePem);
  if (!createVerify("RSA-SHA256").update(input).verify(publicPem, signature))
    throw new Error("The signature does not verify");
  return { input, signature };
}
const signedAt = now - AGE;
const first = sign(signedAt);
const second = sign(signedAt + 1);
const text = (value) => Buffer.from(value, "latin1");
const fields = (value) => array(limbs(value, 18), "        ");
const email = (
  name,
  at,
  signature,
) => `pub fn ${name}() -> ZkemailReceivedEmail {
    ZkemailReceivedEmail {
        modulus: ${fields(modulus)},
        redc: ${fields(redc(modulus))},
        domain: ${bounded(text(DOMAIN), 64)},
        selector: ${bounded(text(SELECTOR), 64)},
        sender: ${bounded(text(SENDER), 96)},
        recipient: ${bounded(text(RECIPIENT), 96)},
        subject: ${bounded(text(SUBJECT), 128)},
        signed_at: ${at},
        body_hash: ${array([...bodyHash])},
        signature: ${fields(big(signature))},
    }
}
`;
// Another well-formed 2048-bit modulus (n + 2) with its Barrett parameter,
// for a wrong-key test that reaches the signature check.
const other = modulus + 2n;
const fixture = `//! Generated by scripts/fixtures/generators/zkemail_event.mjs; see fixtures/manifest.json. Do not edit.
//! Two synthetic received emails signed with the public synthetic RS256 test
//! key in ${keys}. No mail domain signed them.
use ${adapter.crate}::ZkemailReceivedEmail;

/// The verifier time the emails were made for.
pub global NOW: u64 = ${now};
/// DKIM \`t=\` of \`email()\`; \`second_email()\` is signed one second later.
pub global SIGNED_AT: u64 = ${signedAt};

/// Another well-formed 2048-bit RSA modulus and its Barrett parameter (the
/// fixture key's modulus + 2). No email is signed under it.
pub global OTHER_MODULUS: [Field; 18] = ${array(limbs(other, 18), "")};
pub global OTHER_REDC: [Field; 18] = ${array(limbs(redc(other), 18), "")};

/// From ${SENDER} to ${RECIPIENT}, subject "${SUBJECT}".
${email("email", signedAt, first.signature)}
/// The same message signed again at \`t = SIGNED_AT + 1\`: another event.
${email("second_email", signedAt + 1, second.signature)}`;

await writeFixture({
  instance: values.instance,
  useCase,
  scheme,
  fixture,
  inputs: [
    `${keys}/synthetic-rs256-private.pem`,
    `${keys}/synthetic-rs256-public.pem`,
    generator,
    "aztec/use-cases/scripts/fixtures/generators/event.mjs",
  ],
  record: {
    kind: "synthetic",
    generator: {
      argv: [
        "node",
        "scripts/fixtures/generators/zkemail_event.mjs",
        "--instance",
        values.instance,
        "--now",
        String(now),
      ],
      cwd: "aztec/use-cases",
      library:
        "node:crypto RSA-SHA256 PKCS#1 v1.5 over the adapter's DKIM signing input",
    },
    key_provenance: `Public synthetic RS256 test key committed in ${keys}; not a DKIM key of any mail domain. Anyone can sign with it.`,
    claims: {
      domain: DOMAIN,
      selector: SELECTOR,
      sender: SENDER,
      recipient: RECIPIENT,
      subject: SUBJECT,
      body: BODY,
      body_hash_base64: bodyHash.toString("base64"),
      signed_at: [signedAt, signedAt + 1],
      signing_input: signingInput(signedAt),
      signing_input_sha256: [sha256(first.input), sha256(second.input)],
    },
    notes: [
      `t= is ${AGE} s before --now (and one second later for the second email).`,
      "The generator verifies each signature with node:crypto before writing.",
      "Negative cases mutate this fixture in src/test.nr.",
    ],
  },
});
