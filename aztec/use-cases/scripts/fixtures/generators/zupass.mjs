// Writes src/fixture.nr and fixtures/manifest.json of account-authorisation/zupass:
// a synthetic POD whose `owner` entry names a holder EdDSA-Poseidon key, and
// that holder key's signature on a holder approval POD with the entries
// `_aztec_auth_v1_account`, `_aztec_auth_v1_action` and
// `_aztec_auth_v1_expires` (credentials `signHolderApproval`).
//
// node scripts/fixtures/generators/zupass.mjs --instance account-authorisation/zupass \
//     --account <field hex> --action <field hex>
//
// The issuer and holder keys are derived from public seeds. Needs `npm ci`
// and `npm run build` in packages/credential-proofs-inputs (@pcd/pod 0.5.1).
import {
  credentials,
  options,
  repository,
  require,
  seed,
  write,
} from "./account.mjs";

const ENTRY = "owner";
const values = options({ account: { type: "string" } });
const accountHex = (values.account ?? "")
  .replace(/^0x/, "")
  .toLowerCase()
  .padStart(64, "0");
if (!/^[0-9a-f]{64}$/.test(accountHex))
  throw new Error("Pass --account <field as hex>");
const {
  POD,
  decodePublicKey,
  decodeSignature,
  deriveSignerPublicKey,
  signPODRoot,
} = require("@pcd/pod");
const {
  holderApprovalEntries,
  holderApprovalWitness,
  podToCircuitWitness,
  signHolderApproval,
} = await import(`credential-proofs-inputs/zupass`);
const issuerKey = seed("zupass account issuer key v1").toString("hex");
const holderKey = seed("zupass account holder key v1").toString("hex");
const otherHolderKey = seed("zupass account other holder key v1").toString(
  "hex",
);
const holder = deriveSignerPublicKey(holderKey);
const pod = POD.sign(
  {
    [ENTRY]: { type: "eddsa_pubkey", value: holder },
    eventName: { type: "string", value: "Synthetic event" },
    ticketId: { type: "int", value: 42n },
  },
  issuerKey,
);
const witness = podToCircuitWitness(pod.toJSON(), ENTRY);
// The approval expires at 2100-01-01T00:00:00Z (exclusive).
const EXPIRES = 4102444800n;
const approval = {
  account: BigInt(`0x${accountHex}`),
  action: BigInt(`0x${values.action}`),
  expires: EXPIRES,
};
const point = (encoded) => decodePublicKey(encoded).map(String);
const parts = (encoded) => {
  const s = decodeSignature(encoded);
  return { rx: s.R8[0].toString(), ry: s.R8[1].toString(), s: s.S.toString() };
};
const approvalPod = signHolderApproval(approval, holderKey);
const holderSig = holderApprovalWitness(approvalPod, holder).signature;
const otherSig = {
  key: point(deriveSignerPublicKey(otherHolderKey)),
  ...holderApprovalWitness(signHolderApproval(approval, otherHolderKey))
    .signature,
};
// Signatures that the account must reject: the raw field signature over the
// action (a bare action-signature relation would accept it), and an approval for another account.
const rawSig = parts(signPODRoot(approval.action, holderKey).signature);
const otherAccountSig = parts(
  POD.sign(
    holderApprovalEntries({ ...approval, account: approval.account + 1n }),
    holderKey,
  ).signature,
);
const [hx, hy] = point(holder);
const otherIssuer = point(
  deriveSignerPublicKey(
    seed("zupass account other issuer key v1").toString("hex"),
  ),
);
const list = (items) => `[${items.join(", ")}]`;

const fixture = `//! Generated by scripts/fixtures/generators/zupass.mjs; see fixtures/manifest.json. Do not edit.
//! A synthetic POD and holder signature under EdDSA-Poseidon keys derived
//! from public seeds. They are not Zupass keys; anyone can sign with them.
use crate::ZupassAccount::{AuthInput, AuthPolicy};

/// The account address and the action hash that the holder approval names.
pub global ACCOUNT: Field = 0x${accountHex};
pub global ACTION: Field = 0x${values.action};
/// The approval's \`_aztec_auth_v1_expires\` entry (exclusive, Unix seconds).
pub global EXPIRES: u64 = ${EXPIRES};

/// The holder's raw signature over the action field, which the account rejects.
pub global RAW_ACTION_RX: Field = ${rawSig.rx};
pub global RAW_ACTION_RY: Field = ${rawSig.ry};
pub global RAW_ACTION_S: Field = ${rawSig.s};
/// The holder's signature on the approval POD for account + 1.
pub global OTHER_ACCOUNT_RX: Field = ${otherAccountSig.rx};
pub global OTHER_ACCOUNT_RY: Field = ${otherAccountSig.ry};
pub global OTHER_ACCOUNT_S: Field = ${otherAccountSig.s};

/// Another holder key, which the POD does not name, and its valid signature
/// on the same approval POD.
pub global OTHER_HOLDER_X: Field = ${otherSig.key[0]};
pub global OTHER_HOLDER_Y: Field = ${otherSig.key[1]};
pub global OTHER_HOLDER_RX: Field = ${otherSig.rx};
pub global OTHER_HOLDER_RY: Field = ${otherSig.ry};
pub global OTHER_HOLDER_S: Field = ${otherSig.s};
/// Another issuer public key. Nothing is signed under it.
pub global OTHER_ISSUER_X: Field = ${otherIssuer[0]};
pub global OTHER_ISSUER_Y: Field = ${otherIssuer[1]};

pub fn auth() -> AuthInput {
    AuthInput {
        policy: AuthPolicy {
            issuer_x: ${witness.issuer.x},
            issuer_y: ${witness.issuer.y},
            holder_name_hash: ${witness.name_hash},
            content_id: ${witness.content_id},
        },
        issuer_rx: ${witness.signature.rx},
        issuer_ry: ${witness.signature.ry},
        issuer_s: ${witness.signature.s},
        holder_x: ${hx},
        holder_y: ${hy},
        depth: ${witness.depth},
        indices: ${list(witness.indices)},
        siblings: ${list(witness.siblings)},
        expires: ${EXPIRES},
        holder_rx: ${holderSig.rx},
        holder_ry: ${holderSig.ry},
        holder_s: ${holderSig.s},
    }
}
`;

await write({
  instance: values.instance,
  generator: "zupass.mjs",
  argv: ["--account", accountHex, "--action", values.action],
  library: `${credentials}/src/zupass.ts podToCircuitWitness, signHolderApproval and holderApprovalWitness; @pcd/pod 0.5.1 POD.sign and signPODRoot`,
  inputs: [`${credentials}/src/zupass.ts`],
  keyProvenance:
    "EdDSA-Poseidon keys sha256('credential-proofs synthetic zupass account issuer key v1'), '... holder key v1', '... other holder key v1' and '... other issuer key v1'; public seeds, not Zupass keys. Anyone can sign with them.",
  claims: {
    entry: ENTRY,
    holder_public_key: holder,
    issuer_public_key: pod.signerPublicKey,
    content_id: witness.content_id,
    holder_approval: approvalPod,
  },
  notes: [
    "The holder signs a holder approval POD with the account, action and expires entries; the raw action signature is a negative case.",
  ],
  fixture,
});
