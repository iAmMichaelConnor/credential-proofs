#!/usr/bin/env python3
"""Write the Ed25519 identity-R edge vectors used by noir/ed25519_auth_slow_tests/src/tests.nr.

Public test-only key: RFC 8032 seed 32 x 0x2a, message "PhilSys local test" (the
same key as scripts/fixtures/generate-ed25519-local.mjs). An identity R means
nonce 0, so S = k * a mod ell with k = SHA512(R || A || M) mod ell.

- canonical: R bytes 01 00..00, the RFC 8032 encoding of the identity (valid).
- x_eq_p: R bytes 01 00..00 80, the bytes that compress() binds for a hint with
  x limbs equal to p (an alias of x = 0). S is a correct signature over these R
  bytes, so only the strict hint bound rejects it.

Writes noir/ed25519_auth_slow_tests/src/edge_vectors.nr.
"""

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

P = 2**255 - 19
ELL = 2**252 + 27742317777372353535851937790883648493
D = (-121665 * pow(121666, -1, P)) % P
B = (
    15112221349535400772501151409588531511454012693041857206046113283949847762202,
    4 * pow(5, -1, P) % P,
)


def add(p1, p2):
    x1, y1 = p1
    x2, y2 = p2
    t = D * x1 * x2 * y1 * y2 % P
    return (
        (x1 * y2 + y1 * x2) * pow(1 + t, -1, P) % P,
        (y1 * y2 + x1 * x2) * pow(1 - t, -1, P) % P,
    )


def mul(k, point):
    acc = (0, 1)
    while k:
        if k & 1:
            acc = add(acc, point)
        point = add(point, point)
        k >>= 1
    return acc


def encode(point):
    x, y = point
    out = bytearray(y.to_bytes(32, "little"))
    out[31] |= (x & 1) << 7
    return bytes(out)


# The public key of the seed, as in the fixtures of tests.nr.
KEY = [
    25, 127, 107, 35, 225, 108, 133, 50, 198, 171, 200, 56, 250, 205, 94, 167,
    137, 190, 12, 118, 178, 146, 3, 52, 3, 155, 250, 139, 61, 54, 141, 97,
]


def main():
    seed = bytes([42] * 32)
    h = hashlib.sha512(seed).digest()
    a = int.from_bytes(h[:32], "little")
    a &= (1 << 254) - 8
    a |= 1 << 254
    public = encode(mul(a, B))
    message = b"PhilSys local test"
    assert list(public) == KEY, "the test key changed"
    out = [
        "// Generated by scripts/fixtures/generate-ed25519-edge-vectors.py; do not edit.",
        "// Signatures with an identity R (nonce 0) by the RFC 8032 test seed 32 x 0x2a",
        '// over "PhilSys local test".',
    ]
    for name, r_bytes, doc in (
        ("IDENTITY_R_SIGNATURE", bytes([1]) + bytes(31), "R = 01 00..00, the RFC 8032 encoding of the identity."),
        (
            "X_EQ_P_SIGNATURE",
            bytes([1]) + bytes(30) + bytes([128]),
            "R = 01 00..00 80, the bytes compress() binds for x limbs equal to p.",
        ),
    ):
        k = (
            int.from_bytes(
                hashlib.sha512(r_bytes + public + message).digest(), "little"
            )
            % ELL
        )
        s = k * a % ELL
        # Self-check of the cofactorless relation [S]B = R + [k]A with R = O.
        assert mul(s, B) == mul(k, mul(a, B))
        signature = ", ".join(map(str, r_bytes + s.to_bytes(32, "little")))
        out.append(f"/// {doc}\npub global {name}: [u8; 64] = [{signature}];")
    path = ROOT / "noir/ed25519_auth_slow_tests/src/edge_vectors.nr"
    path.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
