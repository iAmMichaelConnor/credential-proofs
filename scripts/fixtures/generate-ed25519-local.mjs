/** Public deterministic local fixture and RFC8032 tests, never issuer-issued. */
import { createPrivateKey, createPublicKey, sign } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { importVerifiedEd25519 } from "credential-proofs-inputs/ed25519";

import { boundedBytes, stringifyToml } from "credential-proofs-inputs/toml";


const sk = createPrivateKey({
  key: Buffer.concat([
    Buffer.from("302e020100300506032b657004220420", "hex"),
    Buffer.alloc(32, 42),
  ]),
  format: "der",
  type: "pkcs8",
});
const key = Buffer.from(
    createPublicKey(sk).export({ format: "jwk" }).x,
    "base64url",
  ),
  message = Buffer.from("PhilSys local test"),
  signature = sign(null, message, sk);
const imported = importVerifiedEd25519(message, signature, key);

const vectors = JSON.parse(
  await readFile(
    new URL(
      "../../fixtures/material/ed25519/provider-test/rfc8032-vectors.json",
      import.meta.url,
    ),
    "utf8",
  ),
);
const bytes = (hex) => {
  if (!/^(?:[0-9a-f]{2})*$/.test(hex)) throw Error("Invalid RFC vector hex");
  return Buffer.from(hex, "hex");
};
const array = (values) => "[" + values.join(",") + "]";
const hint = (value) =>
  "PointHint {x_limbs: std::hint::black_box(" +
  array(value.x_limbs) +
  "),y_limbs: std::hint::black_box(" +
  array(value.y_limbs) +
  ")}";
let tests =
  "// Generated by scripts/fixtures/generate-ed25519-local.mjs.\n" +
  "// Exact public RFC8032 section7.1 vectors; no signing keys are needed.\n" +
  "use ed25519_auth::{PointHint, verify};\n";
const ids = new Set();
for (const vector of vectors.vectors) {
  if (!/^[a-zA-Z0-9_]+$/.test(vector.id) || ids.has(vector.id))
    throw Error("Invalid or duplicate RFC vector id");
  ids.add(vector.id);
  const input = importVerifiedEd25519(
    bytes(vector.messageHex),
    bytes(vector.signatureHex),
    bytes(vector.publicKeyHex),
  );
  const name = /^\d+$/.test(vector.id) ? "test" + vector.id : vector.id;
  tests +=
    `// RFC case ${vector.id}: ${input.message.length} message bytes.\n` +
    `#[test]\nfn rfc8032_${name}() {\n` +
    `let public_key: [u8;32] = std::hint::black_box(${array(input.public_key)});\n` +
    `let signature: [u8;64] = std::hint::black_box(${array(input.signature)});\n` +
    `let message: [u8;${input.message.length}] = std::hint::black_box(${array(input.message)});\n` +
    `verify::<${input.message.length}>(public_key,signature,BoundedVec::from_array(message),${hint(input.public_hint)},${hint(input.signature_hint)});\n` +
    "}\n";
}
await writeFile(
  new URL("../../target/kat/ed25519/Prover.toml", import.meta.url),
  stringifyToml({
    key: imported.public_key,
    signature: imported.signature,
    message: boundedBytes(message, 18),
    key_hint: imported.public_hint,
    signature_hint: imported.signature_hint,
  }),
);
await writeFile(
  new URL("../../noir/ed25519_auth_slow_tests/src/rfc_tests.nr", import.meta.url),
  tests,
);
console.log(
  `Generated deterministic local Ed25519 witness and ${ids.size} verified RFC8032 tests; private seed is public test-only.`,
);
