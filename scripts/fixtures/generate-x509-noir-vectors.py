#!/usr/bin/env python3
"""Write generated X.509 path-length and certificate-policy test vectors.

Synthetic vectors are built from DER primitives. No network or private keys.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = "// Generated by scripts/fixtures/generate-x509-noir-vectors.py. Do not edit.\n"


def der_len(n):
    if n < 128:
        return bytes([n])
    body = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([0x80 | len(body)]) + body


def tlv(tag, content):
    return bytes([tag]) + der_len(len(content)) + content


def noir_bytes(b):
    return ", ".join(str(x) for x in b)


def vec_fn(name, b, doc):
    return f"/// {doc}\npub fn {name}() -> BoundedVec<u8, {len(b)}> {{\n    BoundedVec::from_array([{noir_bytes(b)}])\n}}\n"


def basic_constraints_extensions(path_len):
    bc = tlv(0x01, b"\xff") + (tlv(0x02, path_len) if path_len is not None else b"")
    ext_bc = tlv(
        0x30,
        tlv(0x06, bytes([85, 29, 19])) + tlv(0x01, b"\xff") + tlv(0x04, tlv(0x30, bc)),
    )
    ext_ku = tlv(
        0x30,
        tlv(0x06, bytes([85, 29, 15]))
        + tlv(0x01, b"\xff")
        + tlv(0x04, tlv(0x03, b"\x01\x06")),
    )
    return tlv(0xA3, tlv(0x30, ext_ku + ext_bc))


def path_len_vectors():
    cases = [
        ("ca_path_len_absent", None, "CA:TRUE without pathLenConstraint."),
        ("ca_path_len_0", b"\x00", "CA:TRUE, pathLenConstraint 0."),
        ("ca_path_len_1", b"\x01", "CA:TRUE, pathLenConstraint 1."),
        (
            "ca_path_len_128",
            b"\x00\x80",
            "CA:TRUE, pathLenConstraint 128 (minimal two-byte INTEGER).",
        ),
        (
            "ca_path_len_nonminimal_5",
            b"\x00\x05",
            "CA:TRUE, pathLenConstraint 5 encoded as 02 02 00 05 (not minimal DER).",
        ),
        ("ca_path_len_empty", b"", "CA:TRUE, empty pathLenConstraint INTEGER."),
        ("ca_path_len_negative", b"\x80", "CA:TRUE, pathLenConstraint -128."),
    ]
    return HEADER + "\n".join(
        vec_fn(n, basic_constraints_extensions(v), doc) for n, v, doc in cases
    )


def extension(oid, value):
    return tlv(48, tlv(6, bytes(oid)) + tlv(4, value))


def policy_extensions(ids, ca=False):
    ku = extension([85, 29, 15], tlv(3, bytes([2, 4]) if ca else bytes([7, 128])))
    bc = extension([85, 29, 19], tlv(48, tlv(1, b"\xff") if ca else b""))
    policies = extension(
        [85, 29, 32], tlv(48, b"".join(tlv(48, tlv(6, oid)) for oid in ids))
    )
    return tlv(163, tlv(48, ku + bc + policies))


def policy_vectors():
    policy = bytes([42, 131, 8, 140, 155, 85, 8, 5, 1, 3, 30])

    cases = [
        ("matching_then_short", [policy, b"\x2a"]),
        ("short_then_matching", [b"\x2a", policy]),
        ("short_only", [b"\x2a"]),
        ("empty_only", [b""]),
        ("matching_then_empty", [policy, b""]),
        ("matching_only", [policy]),
    ]
    return (
        HEADER
        + "\n".join(
            vec_fn(
                name,
                policy_extensions(ids),
                "Purpose policy comparison boundary vector.",
            )
            for name, ids in cases
        )
        + "\n"
        + "\n".join(
            vec_fn(name, policy_extensions(ids, True), "CA optional policy vector.")
            for name, ids in [("ca_matching_only", [policy]), ("ca_empty_only", [b""])]
        )
    )


OUTPUTS = {
    ROOT / "noir/x509_auth/src/path_len_vectors.nr": path_len_vectors,
    ROOT / "noir/x509_auth/src/policy_vectors.nr": policy_vectors,
}


def main():
    for path, build in OUTPUTS.items():
        path.write_text(build())


if __name__ == "__main__":
    main()
