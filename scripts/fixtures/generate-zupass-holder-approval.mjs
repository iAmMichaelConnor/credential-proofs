// Writes the holder approval test vectors of noir/zupass
// (src/tests/holder_approval_fixture.nr) and the signed approval POD
// (fixtures/data/zupass/holder-approval.pod.json), and the holder
// login test vectors (src/tests/holder_login_fixture.nr).
//
// node scripts/fixtures/generate-zupass-holder-approval.mjs
//
// Needs `npm ci` and `npm run build` at the repository root
// (@pcd/pod 0.5.1). The keys are derived from public seeds; anyone can sign
// with them. No network access, no proving.
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const auth = fileURLToPath(new URL("../../", import.meta.url));
const require = createRequire(`${auth}packages/credential-proofs-inputs/package.json`);
const {
  POD,
  decodePublicKey,
  decodeSignature,
  deriveSignerPublicKey,
  signPODRoot,
} = require("@pcd/pod");
const {
  holderApprovalEntries,
  holderApprovalWitness,
  holderLoginEntries,
  holderLoginWitness,
  podToCircuitWitness,
  signHolderApproval,
  signHolderLogin,
} = await import(`${auth}packages/credential-proofs-inputs/dist/src/zupass.js`);

const key = (label) =>
  createHash("sha256")
    .update(`credential-proofs synthetic zupass library ${label}`)
    .digest("hex");
const field = (label) =>
  BigInt(
    `0x${createHash("sha256").update(`credential-proofs synthetic zupass library ${label}`).digest("hex")}`,
  ) >> 8n;
const issuerKey = key("issuer key v1");
const holderKey = key("holder key v1");
const otherHolderKey = key("other holder key v1");
const holder = deriveSignerPublicKey(holderKey);

// The issuer POD names the holder key in `owner`.
const issuerPod = POD.sign(
  {
    owner: { type: "eddsa_pubkey", value: holder },
    ticketId: { type: "int", value: 7n },
  },
  issuerKey,
);
const certified = podToCircuitWitness(issuerPod.toJSON(), "owner");

const approval = {
  account: field("account v1"),
  action: field("action v1"),
  expires: 4102444800n,
};
const approvalPod = signHolderApproval(approval, holderKey);
const witness = holderApprovalWitness(approvalPod, holder);
const sig = (encoded) => {
  const s = decodeSignature(encoded);
  return { rx: s.R8[0].toString(), ry: s.R8[1].toString(), s: s.S.toString() };
};
const signed = (entries, privateKey) => POD.sign(entries, privateKey).signature;

// Signatures that the relation must reject.
const rawAction = signPODRoot(approval.action, holderKey).signature;
const otherHolder = holderApprovalWitness(
  signHolderApproval(approval, otherHolderKey),
);
const otherAccount = signed(
  holderApprovalEntries({ ...approval, account: approval.account + 1n }),
  holderKey,
);
const extraEntry = signed(
  {
    ...holderApprovalEntries(approval),
    _aztec_auth_v1_note: { type: "int", value: 1n },
  },
  holderKey,
);
const otherHolderPoint = decodePublicKey(
  deriveSignerPublicKey(otherHolderKey),
).map(String);

const signature = (name, s, doc) => `/// ${doc}
pub global ${name}: Signature = Signature {
    rx: ${s.rx},
    ry: ${s.ry},
    s: ${s.s},
};
`;
const list = (items) => `[${items.join(", ")}]`;
const point = (p) => `PublicKey {\n    x: ${p.x},\n    y: ${p.y},\n}`;
const nr = `//! Generated by scripts/fixtures/generate-zupass-holder-approval.mjs. Do not edit.
//! Synthetic EdDSA-Poseidon keys derived from public seeds; anyone can sign
//! with them. @pcd/pod 0.5.1 signs both PODs.
use crate::{HolderApproval, PublicKey, Signature};

/// The issuer POD {owner: holder key, ticketId: 7}.
pub global CONTENT_ID: Field =
    ${certified.content_id};
pub global ISSUER: PublicKey = ${point(certified.issuer)};
pub global ISSUER_SIGNATURE: Signature = Signature {
    rx: ${certified.signature.rx},
    ry: ${certified.signature.ry},
    s: ${certified.signature.s},
};
pub global OWNER_NAME_HASH: Field =
    ${certified.name_hash};
pub global DEPTH: u32 = ${certified.depth};
pub global INDICES: [bool; 8] = ${list(certified.indices)};
pub global SIBLINGS: [Field; 8] = [
${certified.siblings.map((s) => `    ${s},\n`).join("")}];

pub global HOLDER: PublicKey = ${point(witness.holder)};
pub global OTHER_HOLDER: PublicKey = ${point({ x: otherHolderPoint[0], y: otherHolderPoint[1] })};

/// The approval that the holder signs as a POD.
pub global APPROVAL: HolderApproval = HolderApproval {
    account: ${witness.account},
    action: ${witness.action},
    expires: ${witness.expires},
};
/// The approval POD's content ID as @pcd/pod computes it.
pub global APPROVAL_CONTENT_ID: Field =
    ${witness.content_id};
${signature("APPROVAL_SIGNATURE", witness.signature, "The holder's signature on the approval POD.")}
${signature("OTHER_HOLDER_APPROVAL_SIGNATURE", otherHolder.signature, "Another holder key's signature on the same approval POD.")}
${signature("RAW_ACTION_SIGNATURE", sig(rawAction), "The holder's raw `signPODRoot` signature over the action field.")}
${signature("OTHER_ACCOUNT_SIGNATURE", sig(otherAccount), "The holder's signature on the approval POD with account + 1.")}
${signature("EXTRA_ENTRY_SIGNATURE", sig(extraEntry), "The holder's signature on the approval POD plus the entry `_aztec_auth_v1_note: 1`.")}`;

await writeFile(
  `${auth}noir/zupass/src/tests/holder_approval_fixture.nr`,
  nr,
);
await writeFile(
  `${auth}fixtures/data/zupass/holder-approval.pod.json`,
  `${JSON.stringify(approvalPod, null, 2)}\n`,
);

// Holder login: the same issuer POD and holder key.
const login = { challenge: field("challenge v1"), issuedAt: 3999999940n };
const loginWitness = holderLoginWitness(
  signHolderLogin(login, holderKey),
  holder,
);
const otherHolderLogin = holderLoginWitness(
  signHolderLogin(login, otherHolderKey),
);
const rawChallenge = signPODRoot(login.challenge, holderKey).signature;
const extraLoginEntry = signed(
  {
    ...holderLoginEntries(login),
    _aztec_link_v1_note: { type: "int", value: 1n },
  },
  holderKey,
);
// An approval POD whose action is the challenge and whose expiry is the issue time.
const approvalAsLogin = signed(
  holderApprovalEntries({
    account: approval.account,
    action: login.challenge,
    expires: login.issuedAt,
  }),
  holderKey,
);
const loginNr = `//! Generated by scripts/fixtures/generate-zupass-holder-approval.mjs. Do not edit.
//! Synthetic EdDSA-Poseidon keys derived from public seeds; anyone can sign
//! with them. @pcd/pod 0.5.1 signs the PODs. The issuer POD, holder and other
//! holder are those of holder_approval_fixture.nr.
use crate::{HolderLogin, Signature};
/// The login that the holder signs as a POD.
pub global LOGIN: HolderLogin = HolderLogin {
    challenge: ${loginWitness.challenge},
    issued_at: ${loginWitness.issued_at},
};
/// The login POD's content ID as @pcd/pod computes it.
pub global LOGIN_CONTENT_ID: Field =
    ${loginWitness.content_id};
${signature("LOGIN_SIGNATURE", loginWitness.signature, "The holder's signature on the login POD.")}
${signature("OTHER_HOLDER_LOGIN_SIGNATURE", otherHolderLogin.signature, "Another holder key's signature on the same login POD.")}
${signature("RAW_CHALLENGE_SIGNATURE", sig(rawChallenge), "The holder's raw `signPODRoot` signature over the challenge field.")}
${signature("EXTRA_ENTRY_LOGIN_SIGNATURE", sig(extraLoginEntry), "The holder's signature on the login POD plus the entry `_aztec_link_v1_note: 1`.")}
${signature("APPROVAL_AS_LOGIN_SIGNATURE", sig(approvalAsLogin), "The holder's signature on an approval POD with action = challenge and expires = issued_at.")}`;
await writeFile(
  `${auth}noir/zupass/src/tests/holder_login_fixture.nr`,
  loginNr,
);
console.log(`Wrote holder approval fixture, content ID ${witness.content_id}`);
console.log(
  `Wrote holder login fixture, content ID ${loginWitness.content_id}`,
);
