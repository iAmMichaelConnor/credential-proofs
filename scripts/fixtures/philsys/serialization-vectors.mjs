// Writes src/serialization_vectors.nr: SHA-256 digests of the official
// legacy serialization (JSON.stringify(..., null, 2), U+00F1/U+00D1 replaced by `?`,
// Latin-1 bytes, as in the PSA verifier's main.js) of the synthetic fixture
// QR with chosen first names. Independent of the circuit's serializer.
//
// node scripts/fixtures/philsys/serialization-vectors.mjs
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../../../", import.meta.url);
const qr = JSON.parse(
  await readFile(
    new URL(
      "fixtures/material/philsys/local-test/synthetic-legacy-qr.json",
      root,
    ),
    "utf8",
  ),
);
const { signature: _signature, ...fields } = qr;

function digest(firstName) {
  const signed = {
    ...fields,
    subject: { ...fields.subject, fName: firstName },
  };
  const message = Buffer.from(
    JSON.stringify(signed, null, 2).replace(/\u00f1|\u00d1/g, "?"),
    "latin1",
  );
  return [...createHash("sha256").update(message).digest()];
}

const highLatin1 = [32, 126, 128, 160, 208, 210, 240, 242, 255];
const vectors = {
  QUESTION_MARKS_DIGEST: ["first name `??`", digest("??")],
  HIGH_LATIN1_DIGEST: [
    `first name bytes ${JSON.stringify(highLatin1)}`,
    digest(Buffer.from(highLatin1).toString("latin1")),
  ],
};
// The official replacement maps U+00F1 U+00D1 to the same signed bytes as `??`.
if (
  JSON.stringify(digest("\u00f1\u00d1")) !==
  JSON.stringify(vectors.QUESTION_MARKS_DIGEST[1])
)
  throw Error("U+00F1 U+00D1 and ?? must sign the same bytes");

let out =
  "//! Generated by scripts/fixtures/philsys/serialization-vectors.mjs. Do not edit.\n";
out +=
  "//! SHA-256 of the official legacy serialization of the synthetic fixture QR.\n";
out += `pub global HIGH_LATIN1_FIRST_NAME: [u8; ${highLatin1.length}] = [${highLatin1.join(", ")}];\n`;
for (const [name, [doc, bytes]] of Object.entries(vectors)) {
  out += `/// The fixture with ${doc}.\npub global ${name}: [u8; 32] = [${bytes.join(", ")}];\n`;
}
await writeFile(
  new URL("noir/philsys_auth/src/serialization_vectors.nr", root),
  out,
);
console.log("wrote noir/philsys_auth/src/serialization_vectors.nr");
